import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
from common import *


def node(text, color, size=28):
    return pill(text, color, size)


def frac_t(a, b, color=INK, fs=56):
    return MathTex(r"{" + a + r"\over " + b + r"}", font_size=fs, color=color)


class S05Rule(Base):
    CHAPTER = "Bayes' Rule"

    def construct(self):
        fr = self.camera.frame
        # ── s046 counting = Bayes ──
        self.at("s046", 0.0)
        sg = stacks_axes(x_len=3.6, y_len=4.0); sg.move_to(LEFT * 3.6 + UP * 0.3)
        sax = sg.ax
        st_s, st_h = stack(sax, 0.6, 9, ORANGE_), stack(sax, 1.4, 99, BLUE_)
        l9 = TB("9", 40, ORANGE_).next_to(st_s, UP, buff=0.15)
        l99 = TB("99", 40, BLUE_).next_to(st_h, UP, buff=0.15)
        self.play(FadeIn(sg), FadeIn(st_s, lag_ratio=0.05), FadeIn(st_h, lag_ratio=0.005), FadeIn(l9), FadeIn(l99), run_time=1.0)
        eq = TB("=", 80, MUTED).move_to(LEFT * 0.4 + UP * 0.3)
        bk = card(5.2, 2.6, VIOLET).move_to(RIGHT * 3.6 + UP * 0.3)
        bt = TB("Bayes' theorem", 44, VIOLET).move_to(bk)
        self.until(word_time("s046", word_index("s046", "exactly")))
        self.play(FadeIn(eq), FadeIn(bk), Write(bt), run_time=1.0)
        books = T("…the way you'll see it in books", 26, MUTED).next_to(bk, DOWN, buff=0.3)
        self.until(word_time("s046", word_index("s046", "write")) - 0.1)
        self.play(FadeIn(books, shift=UP * 0.2), run_time=0.5)

        # ── s047 the tree: first split ──
        self.at("s047", 0.0)
        self.play(FadeOut(VGroup(sg, st_s, st_h, l9, l99, eq, bk, bt, books)), run_time=0.5)
        root = node("1,000 people", INK, 30).move_to(LEFT * 5.0 + UP * 0.25)
        n_s = node("10 have it", ORANGE_).move_to(LEFT * 1.0 + UP * 1.65)
        n_h = node("990 healthy", BLUE_).move_to(LEFT * 1.0 + DOWN * 1.15)
        e1 = Line(root.get_right(), n_s.get_left(), color=ORANGE_, stroke_width=4)
        e2 = Line(root.get_right(), n_h.get_left(), color=BLUE_, stroke_width=4)
        w1 = MathTex(r"\times\frac{1}{100}", font_size=40, color=ORANGE_).next_to(e1.get_center(), UL, buff=0.08)
        w2 = MathTex(r"\times\frac{99}{100}", font_size=40, color=BLUE_).next_to(e2.get_center(), DL, buff=0.08)
        self.play(FadeIn(root, scale=0.8), run_time=0.5)
        self.until(word_time("s047", word_index("s047", "split")) - 0.1)
        self.play(Create(e1), Create(e2), run_time=0.6)
        self.play(FadeIn(n_s, shift=RIGHT * 0.2), FadeIn(w1), run_time=0.5)
        self.until(word_time("s047", word_index("s047", "nine")) - 0.1)
        self.play(FadeIn(n_h, shift=RIGHT * 0.2), FadeIn(w2), run_time=0.5)
        # ── s048 second split ──
        self.at("s048", 0.0)
        leaves = [("9 positive", ORANGE_, UP * 2.45, True, r"\tfrac{9}{10}"), ("1 negative", MUTED, UP * 0.95, False, r"\tfrac{1}{10}"),
                  ("99 positive", BLUE_, DOWN * 0.35, True, r"\tfrac{1}{10}"), ("891 negative", MUTED, DOWN * 1.85, False, r"\tfrac{9}{10}")]
        L, E, Wt = VGroup(), VGroup(), VGroup()
        for k, (txt, col, y, pos, w) in enumerate(leaves):
            par = n_s if k < 2 else n_h
            lf = node(txt, col, 26).move_to(RIGHT * 3.3 + y)
            if pos:
                lf[0].set_stroke(AQUA, 4)
            e = Line(par.get_right(), lf.get_left(), color=col if col != MUTED else INK2, stroke_width=3)
            wl = MathTex(w.replace("tfrac", "frac"), font_size=38, color=INK2).next_to(e.get_center(), UP if k % 2 == 0 else DOWN, buff=0.08)
            L.add(lf); E.add(e); Wt.add(wl)
        self.play(Create(E[0]), Create(E[1]), run_time=0.5)
        self.play(FadeIn(L[0], shift=RIGHT * 0.2), FadeIn(L[1], shift=RIGHT * 0.2), FadeIn(Wt[0]), FadeIn(Wt[1]), run_time=0.7)
        self.until(word_time("s048", word_index("s048", "Ninety")) - 0.1)
        self.play(Create(E[2]), Create(E[3]), run_time=0.5)
        self.play(FadeIn(L[2], shift=RIGHT * 0.2), FadeIn(L[3], shift=RIGHT * 0.2), FadeIn(Wt[2]), FadeIn(Wt[3]), run_time=0.7)
        # ── s049 positive leaves ──
        self.at("s049", 0.0)
        dim = VGroup(L[1], L[3], E[1], E[3], Wt[1], Wt[3])
        self.play(dim.animate.set_opacity(0.2), run_time=0.6)
        self.qa_mute(dim)
        hl = VGroup(*[glow(L[k][0].copy().set_fill(opacity=0), AQUA, width=16, opacity=0.08) for k in (0, 2)])
        self.play(FadeIn(hl), run_time=0.5)
        br = Brace(VGroup(L[0], L[2]), RIGHT, buff=0.2, color=AQUA)
        bt2 = MathTex(r"{9 \over 9 + 99}", font_size=48, color=VIOLET).next_to(br, RIGHT, buff=0.15)
        self.until(word_time("s049", word_index("s049", "Nine")) - 0.1)
        self.play(GrowFromCenter(br), Write(bt2), run_time=0.8)
        self.play(Indicate(L[0], color=ORANGE_), run_time=0.6)
        self.play(Indicate(L[2], color=BLUE_), run_time=0.6)

        # ── s050–s052 the symbols ──
        self.at("s050", 0.0)
        tree = VGroup(root, n_s, n_h, e1, e2, w1, w2, L, E, Wt, hl, br, bt2)
        self.play(FadeOut(tree), run_time=0.5)
        self.qa_mute(dim, False)
        self.drop(tree)
        hdr = T("the symbols", 30, MUTED, weight=BOLD).move_to(UP * 2.75)
        d1 = defcard(r"P(\;\dots\;)", "the probability of …", INK, fs=28)
        d2 = defcard(r"A", "has the condition", ORANGE_, fs=28)
        d3 = defcard(r"B", "tests positive", AQUA, fs=28)
        d4 = defcard(r"\mid", "given", INK, fs=28)
        d5 = defcard(r"P(A\mid B)", "chance you have it, given a positive test", VIOLET, fs=28)
        d2[1][0].set_color(ORANGE_); d3[1][0].set_color(AQUA); d5[1][0].set_color(VIOLET)
        col = VGroup(d1, d2, d3, d4, d5).arrange(DOWN, buff=0.16, aligned_edge=LEFT).move_to(DOWN * 0.05)
        hdr.next_to(col, UP, buff=0.35)
        self.play(FadeIn(hdr), FadeIn(d1, shift=RIGHT * 0.3), run_time=0.7)
        self.at("s051", 0.0)
        self.play(FadeIn(d2, shift=RIGHT * 0.3), run_time=0.5)
        self.until(word_time("s051", word_index("s051", "B")) - 0.1)
        self.play(FadeIn(d3, shift=RIGHT * 0.3), run_time=0.5)
        self.at("s052", 0.0)
        self.play(FadeIn(d4, shift=RIGHT * 0.3), run_time=0.5)
        self.until(word_time("s052", word_index("s052", "So")) - 0.1)
        self.play(FadeIn(d5, shift=RIGHT * 0.3), run_time=0.6)
        self.play(Circumscribe(d5, color=VIOLET), run_time=1.0)

        # ── s053–s054 the formula ──
        self.at("s053", 0.0)
        F = MathTex(r"P(A\mid B)", r"=", r"{P(B\mid A)", r"\,P(A)", r"\over", r"P(B)}", font_size=96)
        F[0].set_color(VIOLET)
        F.move_to(UP * 0.4)
        self.play(FadeOut(VGroup(col, hdr)), run_time=0.5)
        self.until(word_time("s053", word_index("s053", "here")) - 0.1)
        self.play(Write(F), run_time=1.4)
        self.at("s054", 0.0)
        seq = [(0, "P"), (2, "equals"), (3, "times"), (5, "divided")]
        for idx, w in seq:
            self.until(word_time("s054", word_index("s054", w)) - 0.05)
            self.play(Indicate(F[idx], color=VIOLET if idx == 0 else WARN if idx == 3 else AQUA if idx == 2 else INK, scale_factor=1.15),
                      run_time=0.8)

        # ── s055–s060 match each piece to the crowd ──
        self.at("s055", 0.0)
        self.play(F.animate.scale(0.8).move_to(UP * 2.05), run_time=0.7)
        conn = DashedLine(F.get_bottom() + DOWN * 0.1, F.get_bottom() + DOWN * 0.7, color=MUTED)
        crowd_t = T("our crowd of 1,000", 28, MUTED).next_to(conn, DOWN, buff=0.12)
        self.play(Create(conn), FadeIn(crowd_t), run_time=0.6)
        self.at("s056", 0.0)
        self.play(FadeOut(VGroup(conn, crowd_t)), F[3].animate.set_color(WARN), run_time=0.5)
        v_a = VGroup(MathTex(r"P(A)", font_size=52, color=WARN), MathTex("=", font_size=52),
                     frac_t("10", "1000", WARN, 52)).arrange(RIGHT, buff=0.2)
        lab_a = T("base rate", 26, WARN).next_to(v_a, DOWN, buff=0.2)
        ga = VGroup(v_a, lab_a).move_to(LEFT * 4.3 + DOWN * 0.6)
        self.play(TransformFromCopy(F[3], v_a[0]), FadeIn(v_a[1:]), FadeIn(lab_a), run_time=0.9)
        self.at("s057", 0.0)
        self.play(F[2].animate.set_color(AQUA), run_time=0.4)
        v_b = VGroup(MathTex(r"P(B\mid A)", font_size=52, color=AQUA), MathTex("=", font_size=52),
                     frac_t("9", "10", AQUA, 52)).arrange(RIGHT, buff=0.2)
        lab_b = T("how good the test is at catching it", 26, AQUA).next_to(v_b, DOWN, buff=0.2)
        gb = VGroup(v_b, lab_b).move_to(RIGHT * 0.2 + DOWN * 0.6)
        self.play(TransformFromCopy(F[2], v_b[0]), FadeIn(v_b[1:]), FadeIn(lab_b), run_time=0.9)
        self.at("s058", 0.0)
        prod = MathTex(r"{9\over 10}", r"\times", r"{10\over 1000}", "=", r"{9\over 1000}", font_size=52)
        prod[0].set_color(AQUA); prod[2].set_color(WARN); prod[4].set_color(ORANGE_)
        prod.move_to(DOWN * 0.6 + LEFT * 1.6)
        self.play(FadeOut(VGroup(lab_a, lab_b)), ReplacementTransform(VGroup(v_a, v_b), prod[:3]), run_time=0.9)
        self.play(Write(prod[3:]), run_time=0.6)
        mini = VGroup(*[Square(0.28, stroke_width=0, fill_color=ORANGE_, fill_opacity=1) for _ in range(9)]).arrange(RIGHT, buff=0.06)
        mini.next_to(prod, RIGHT, buff=0.6)
        tpl = T("true positives", 26, ORANGE_).next_to(mini, DOWN, buff=0.2)
        self.play(LaggedStart(*[FadeIn(m, scale=0.5) for m in mini], lag_ratio=0.08), FadeIn(tpl), run_time=0.8)
        self.at("s059", 0.0)
        ul = Underline(F[5], color=INK, buff=0.08)
        self.play(Create(ul), run_time=0.5)
        v_c = VGroup(MathTex(r"P(B)", font_size=52), MathTex("=", font_size=52), frac_t("108", "1000", INK, 52)).arrange(RIGHT, buff=0.2)
        lab_c = T("chance of testing positive at all (real or false)", 26, INK2).next_to(v_c, DOWN, buff=0.2)
        gc = VGroup(v_c, lab_c).move_to(DOWN * 0.7)
        self.until(word_time("s059", word_index("s059", "Real")) - 0.1)
        self.play(FadeOut(VGroup(prod, mini, tpl)), FadeIn(gc, shift=UP * 0.2), run_time=0.7)
        self.at("s060", 0.0)
        res = MathTex(r"{9/1000 \over 108/1000}", "=", r"{9 \over 108}", r"\approx", r"8.3\%", font_size=60)
        res[0].set_color(INK); res[2:].set_color(VIOLET)
        res.move_to(DOWN * 0.7)
        self.play(FadeOut(VGroup(gc, ul)), run_time=0.5)
        self.play(Write(res[0]), run_time=0.8)
        self.until(word_time("s060", word_index("s060", "Nine")) - 0.1)
        self.play(Write(res[1:3]), run_time=0.6)
        self.play(Write(res[3:]), run_time=0.5)
        self.until(word_time("s060", word_index("s060", "same")) - 0.1)
        sm = VGroup(check(AQUA, 0.35), T("same as counting", 28, AQUA)).arrange(RIGHT, buff=0.2).next_to(res, DOWN, buff=0.45)
        self.play(FadeIn(sm), run_time=0.5)
        # ── s061 plain words ──
        self.at("s061", 0.0)
        pw = VGroup(T("real positives", 40, ORANGE_, weight=BOLD), T("÷", 40, MUTED), T("all positives", 40, AQUA, weight=BOLD))
        pw.arrange(RIGHT, buff=0.3).move_to(DOWN * 0.7)
        pwc = card(pw.width + 0.9, pw.height + 0.7, INK2).move_to(pw)
        self.play(FadeOut(VGroup(res, sm)), run_time=0.4)
        self.play(FadeIn(pwc), FadeIn(pw, shift=UP * 0.2), run_time=0.7)
        # ── s062 the bottom hides the false alarms ──
        self.at("s062", 0.0)
        self.play(FadeOut(VGroup(pwc, pw)), F[5].animate.set_color(INK), run_time=0.4)
        boxp = SurroundingRectangle(F[5], color=AQUA, buff=0.1)
        boxp.qa_ignore = True  # deliberate highlight around the denominator term
        inside = VGroup(T("9 real", 34, ORANGE_, weight=BOLD), T("+", 34, MUTED), T("99 false alarms", 34, BLUE_, weight=BOLD))
        inside.arrange(RIGHT, buff=0.3).move_to(DOWN * 0.6)
        arr = Arrow(boxp.get_bottom(), inside.get_top(), buff=0.15, color=AQUA, stroke_width=4)
        self.play(Create(boxp), GrowArrow(arr), run_time=0.6)
        self.play(FadeIn(inside, shift=DOWN * 0.2), run_time=0.6)
        self.play(Indicate(inside[2], color=BLUE_, scale_factor=1.15), run_time=0.7)
        # ── s063 expanded denominator ──
        self.at("s063", 0.0)
        ex = MathTex(r"P(B)", "=", r"P(B\mid A)\,P(A)", "+", r"P(B\mid \text{not }A)\,P(\text{not }A)", font_size=52)
        ex[2].set_color(ORANGE_); ex[4].set_color(BLUE_)
        ex.move_to(DOWN * 0.45)
        nums = MathTex(r"{108 \over 1000}", "=", r"{9 \over 1000}", "+", r"{99 \over 1000}", font_size=48)
        nums[2].set_color(ORANGE_); nums[4].set_color(BLUE_)
        nums.next_to(ex, DOWN, buff=0.55)
        nums.shift(RIGHT * (ex[2].get_center()[0] - nums[2].get_center()[0]))
        self.play(FadeOut(VGroup(inside, arr)), TransformFromCopy(F[5], ex[0]), FadeIn(ex[1:]), run_time=1.0)
        na = pill("not A = healthy", BLUE_, 24).next_to(ex, DOWN, buff=0.55).align_to(ex[4], RIGHT)
        self.play(FadeIn(na), run_time=0.4)
        self.until(word_time("s063", word_index("s063", "true")) - 0.1)
        self.play(Write(nums), run_time=1.2)
        # ── s064 prior / likelihood / posterior ──
        self.at("s064", 0.0)
        self.play(FadeOut(VGroup(ex, nums, na, boxp)), F.animate.scale(0.94).move_to(UP * 0.2 + RIGHT * 1.4), run_time=0.7)
        lp = T("prior", 32, WARN, weight=BOLD).next_to(F[3], UP, buff=0.9).shift(RIGHT * 0.6)
        ll = T("likelihood", 32, AQUA, weight=BOLD).next_to(F[2], UP, buff=0.9).shift(LEFT * 0.6)
        lq = T("posterior", 32, VIOLET, weight=BOLD).next_to(F, LEFT, buff=0.7).set_y(F[0].get_y())
        ap = Arrow(lp.get_bottom(), F[3].get_top(), buff=0.1, color=WARN, stroke_width=4)
        al = Arrow(ll.get_bottom(), F[2].get_top(), buff=0.1, color=AQUA, stroke_width=4)
        aq = Arrow(lq.get_right(), F[0].get_left(), buff=0.12, color=VIOLET, stroke_width=4)
        self.until(word_time("s064", word_index("s064", "prior")) - 0.3)
        self.play(FadeIn(lp, shift=UP * 0.2), GrowArrow(ap), run_time=0.5)
        self.until(word_time("s064", word_index("s064", "posterior")) - 0.3)
        self.play(FadeIn(lq, shift=UP * 0.2), GrowArrow(aq), run_time=0.5)
        self.until(word_time("s064", word_index("s064", "likelihood")) - 0.3)
        self.play(FadeIn(ll, shift=UP * 0.2), GrowArrow(al), run_time=0.5)
        # ── s065 before / after ──
        self.at("s065", 0.0)
        self.play(FadeOut(VGroup(F, ap, al, aq, ll, lp, lq)), run_time=0.5)
        bpr = VGroup(T("prior", 40, WARN, weight=BOLD), T("before the evidence", 26, WARN), TB("1%", 54, WARN)).arrange(DOWN, buff=0.18)
        bpo = VGroup(T("posterior", 40, VIOLET, weight=BOLD), T("after the evidence", 26, VIOLET), TB("8.3%", 54, VIOLET)).arrange(DOWN, buff=0.18)
        bpr.move_to(LEFT * 3.4 + UP * 0.4); bpo.move_to(RIGHT * 3.4 + UP * 0.4)
        ar = Arrow(bpr.get_right(), bpo.get_left(), buff=0.4, color=INK2, stroke_width=5)
        ev = pill("positive test", AQUA, 26).next_to(ar, UP, buff=0.15)
        self.play(FadeIn(bpr, shift=UP * 0.2), run_time=0.6)
        self.play(GrowArrow(ar), FadeIn(ev), run_time=0.5)
        self.play(FadeIn(bpo, shift=UP * 0.2), run_time=0.6)
        self.until(SEGS["s065"]["end"] + 0.5)
        self.play(FadeOut(VGroup(bpr, bpo, ar, ev)), run_time=0.4)
        self.finish()
