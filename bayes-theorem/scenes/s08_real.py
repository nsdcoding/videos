def header(text, color):
    return pill(text, color, 30).move_to(UP * HEAD_Y)


def bump(ax, mu, sd, color, peak_scale=0.42):
    return ax.plot(lambda x: min(0.98, peak_scale / sd) * np.exp(-0.5 * ((x - mu) / sd) ** 2), x_range=[0, 10, 0.05],
                   color=color, stroke_width=5)


