        zone = Rectangle(width=ax.c2p(5, 0)[0] - ax.c2p(0, 0)[0], height=ax.c2p(0, 100)[1] - ax.c2p(0, 0)[1],
                         stroke_width=0, fill_color=RED_, fill_opacity=0.12).move_to(ax.c2p(0, 0), aligned_edge=DL)
