        self.at("s085", 0.0)
        curve_a = ax.plot(lambda x: ppv(x / 100), x_range=[0.3, 10, 0.05], color=VIOLET, stroke_width=5)
        curve_b = ax.plot(lambda x: ppv(x / 100), x_range=[10, 50, 0.25], color=VIOLET, stroke_width=5)
        p1 = Dot(ax.c2p(1, ppv(0.01)), radius=0.09, color=VIOLET)
        l1 = T("1 in 100 → 8%", 24, VIOLET, weight=BOLD).move_to(ax.c2p(14, 14), aligned_edge=LEFT)
        lead1 = Line(p1.get_center(), l1.get_left() + LEFT * 0.08, color=VIOLET, stroke_width=2)
        self.play(Create(curve_a), run_time=1.6, rate_func=linear)
        self.play(FadeIn(p1, scale=2), Create(lead1), FadeIn(l1), run_time=0.4)
        p10 = Dot(ax.c2p(10, ppv(0.1)), radius=0.09, color=VIOLET)
