        self.play(FadeIn(hdr), run_time=0.4)
        self.until(word_time("s085a", word_index("s085a", "hundred")) - 0.2)
        self.play(FadeIn(rA[:2]), run_time=0.4)
        self.until(word_time("s085a", word_index("s085a", "catches")) - 0.1)
        self.play(FadeIn(rA[2:]), run_time=0.4)
        self.at("s085b", 0.0)
        rB = VGroup(TB("900", 30, BLUE_), T("healthy →", 24, BLUE_), TB("90", 30, AQUA), T("false alarms", 24, AQUA)).arrange(RIGHT, buff=0.15, aligned_edge=DOWN)
        rB.next_to(rA, DOWN, buff=0.3).align_to(hdr, LEFT)
        self.play(FadeIn(rB[:2]), run_time=0.4)
        self.until(word_time("s085b", word_index("s085b", "Ninety")) - 0.1)
        self.play(FadeIn(rB[2:]), run_time=0.4)
        mg = stacks_axes(100, 20, x_len=2.4, y_len=2.2, title="positives"); mg.next_to(rB, DOWN, buff=0.55).align_to(hdr, LEFT).shift(RIGHT * 0.5)
