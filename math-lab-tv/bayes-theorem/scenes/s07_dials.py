        rc = card(inner.width + 1.0, inner.height + 0.9, BLUE_).move_to(UP * 0.4)
        inner.move_to(rc)
        self.play(FadeIn(rc), FadeIn(inner, shift=UP * 0.2), run_time=0.8)
        self.until(SEGS["s091"]["end"] + 1.2)
        self.play(FadeOut(VGroup(rc, inner, graph)), run_time=0.5)
        self.finish()
