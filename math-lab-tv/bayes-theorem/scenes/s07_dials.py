        self.play(FadeIn(q), run_time=0.6)
        for d, s_, w in zip(dials, subs, ("base", "hit", "false")):
            self.until(word_time("s083", word_index("s083", w)) - 0.15)
            self.play(FadeIn(VGroup(d[0], d[2], d[3], s_)), Create(d[1]), run_time=0.6)
        # ── s084 axes: base rate → answer ──
        self.at("s084", 0.0)
        axg = xy_axes([0, 50, 10], [0, 100, 20], 6.0, 4.0, "base rate (%)", "chance you have it after a positive (%)", font_size=22)
        axg.move_to(LEFT * 3.2 + UP * 0.45)
        ax = axg.ax
        self.play(FadeOut(VGroup(dials, subs, q)), run_time=0.5)
        self.play(Create(ax), FadeIn(axg.labs), FadeIn(axg.xt), FadeIn(axg.yt), run_time=0.9)
