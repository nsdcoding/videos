        self.play(FadeIn(bm), run_time=0.4)
        self.until(word_time("s090", word_index("s090", "From")) - 0.1)
        self.play(Write(r9), run_time=0.7)
        # ── s091 rule of thumb ──
        self.at("s091", 0.0)
        graph = VGroup(axg, curve_a, curve_b, curve_f, curve_h, p1, l1, lead1, p10, l10, pf, lf, cf_l, hl_)
        self.play(FadeOut(VGroup(hd, bm, r9)), graph.animate.set_opacity(0.15), run_time=0.6)
        self.qa_mute(graph)
        rt = T("rule of thumb", 28, MUTED, weight=BOLD)
        rl1 = T("When the thing is rare,", 40, INK, weight=BOLD)
        rl2 = T("the false alarm rate matters far more than the hit rate.", 34, INK)
