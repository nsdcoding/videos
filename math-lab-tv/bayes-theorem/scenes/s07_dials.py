PX = 0.9


def ppv(b, se=0.9, fp=0.1):
    return 100 * se * b / (se * b + fp * (1 - b))


class S07Dials(Base):
    CHAPTER = "What Moves the Answer"

    def construct(self):
        # ── s083 three dials ──
        self.at("s083", 0.0)
        d1 = gauge(1, WARN, "base rate")
        d2 = gauge(90, AQUA, "hit rate")
        d3 = gauge(10, BLUE_, "false alarm rate")
        dials = VGroup(d1, d2, d3).arrange(RIGHT, buff=1.2).move_to(UP * 0.4)
        subs = VGroup(T("1 in 100", 26, WARN), T("catches 9 of 10", 26, AQUA), T("1 in 10 healthy", 26, BLUE_))
