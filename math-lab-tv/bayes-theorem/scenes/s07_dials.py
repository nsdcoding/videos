        h50 = TB("= 50%", 40, VIOLET).next_to(mg, RIGHT, buff=0.3)
        self.until(word_time("s085b", word_index("s085b", "Fifty")) - 0.1)
        self.play(FadeIn(h50, scale=1.2), run_time=0.4)
        # ── s086 extend to 50%: gut finally right ──
        self.at("s086", 0.0)
        self.play(FadeOut(VGroup(hdr, rA, rB, mg, m1, m2, h50)), run_time=0.4)
        self.play(Create(curve_b), run_time=1.6, rate_func=linear)
