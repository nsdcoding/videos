        fd.move_to(UP * 2.0).align_to(RIGHT * PX, LEFT)
        self.play(FadeIn(fd[0]), FadeIn(fd[1][0]), run_time=0.5)
        self.until(word_time("s088", word_index("s088", "wrongly")) - 0.1)
        self.play(GrowArrow(fd[1][1]), FadeIn(fd[1][2]), run_time=0.6)
        curve_f = ax.plot(lambda x: ppv(x / 100, fp=0.01), x_range=[0.3, 50, 0.1], color=INK, stroke_width=4)
        self.play(Create(curve_f), run_time=1.6, rate_func=linear)
        cf_l = VGroup(Line(LEFT * 0.3, RIGHT * 0.3).set_stroke(INK, 4), T("fewer false alarms (1 in 100)", 22, INK)).arrange(RIGHT, buff=0.15)
        cf_l.move_to(DOWN * 1.75).align_to(RIGHT * PX, LEFT)
        self.play(FadeIn(cf_l), run_time=0.4)
        self.at("s089", 0.0)
        pf = Dot(ax.c2p(1, ppv(0.01, fp=0.01)), radius=0.09, color=INK)
        lf = VGroup()
        cnt = VGroup(T("9 real", 30, ORANGE_, weight=BOLD), T("vs", 26, MUTED), T("about 10 false", 30, BLUE_, weight=BOLD)).arrange(RIGHT, buff=0.2)
        cnt.next_to(fd, DOWN, buff=0.5).align_to(fd, LEFT)
        r48 = MathTex(r"{9 \over 9 + 9.9}", r"\approx", r"48\%", font_size=48, color=VIOLET).next_to(cnt, DOWN, buff=0.35).align_to(fd, LEFT)
        self.play(FadeIn(cnt), run_time=0.5)
        self.until(word_time("s089", word_index("s089", "positive")) - 0.1)
