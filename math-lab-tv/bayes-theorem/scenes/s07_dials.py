        hl_.next_to(cf_l, DOWN, buff=0.2).align_to(cf_l, LEFT)
        self.play(FadeIn(hl_), run_time=0.3)
        bm = T("barely moves", 30, AQUA, weight=BOLD).next_to(hd, DOWN, buff=0.5).align_to(hd, LEFT)
        r9 = MathTex(r"{10 \over 10 + 99}", r"\approx", r"9\%", font_size=48, color=VIOLET).next_to(bm, DOWN, buff=0.35).align_to(hd, LEFT)
