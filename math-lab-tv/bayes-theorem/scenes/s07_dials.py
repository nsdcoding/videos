        self.until(word_time("s085", word_index("s085", "jumps")) - 0.1)
        self.play(FadeIn(p10, scale=2), FadeIn(l10), Flash(p10, color=VIOLET), run_time=0.6)
        # ── s085a/b count it: 1 in 10 ──
        self.at("s085a", 0.0)
        self.play(FadeOut(VGroup(dial_s, same)), run_time=0.4)
        hdr = T("1 in 10, out of 1,000:", 28, INK, weight=BOLD).move_to(UP * 2.55).align_to(RIGHT * PX, LEFT)
        rA = VGroup(TB("100", 30, ORANGE_), T("have it →", 24, ORANGE_), TB("90", 30, AQUA), T("caught", 24, AQUA)).arrange(RIGHT, buff=0.15, aligned_edge=DOWN)
