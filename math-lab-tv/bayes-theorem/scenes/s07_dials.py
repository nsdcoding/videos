        same = T("test stays the same:\ncatches 9 of 10,\nfalse alarm 1 in 10", 24, INK2, line_spacing=0.9).next_to(dial_s, DOWN, buff=0.3).align_to(dial_s, LEFT)
        self.play(FadeIn(dial_s), FadeIn(same), run_time=0.6)
