        gt = T("gut: 90%", 26, MUTED, weight=BOLD).next_to(ax.c2p(50, 90), RIGHT, buff=0.2)
        p50 = Dot(ax.c2p(50, 90), radius=0.1, color=VIOLET)
        hf = T("only when half\nthe people have it", 28, VIOLET, line_spacing=0.9).move_to(UP * 0.9).align_to(RIGHT * PX, LEFT)
        self.play(Create(gl), FadeIn(gt), run_time=0.6)
        self.play(FadeIn(p50, scale=2), Flash(p50, color=VIOLET), FadeIn(hf), run_time=0.7)
        # ── s087 the rarer, the more false alarms win ──
